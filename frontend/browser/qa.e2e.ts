import { test, expect, type Page } from '@playwright/test'

const api = process.env.QA_API!
const ids = JSON.parse(process.env.QA_IDS!) as { orgs: number[]; requirements: number[]; companies: number[]; stages: number[]; signal: number; match: number; candidates: number[] }
const evidence = process.env.QA_EVIDENCE_DIR || '../docs/development/evidence/2026-10-10'
async function signIn(page: Page, email = 'member@example.com') {
  await page.goto('/'); await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Synthetic-QA-password-2026')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
}
async function token(page: Page) { return page.evaluate(() => sessionStorage.getItem('bwip_access_token')!) }
async function shot(page: Page, name: string) {
  await page.screenshot({ path: `${evidence}/${name}.png`, fullPage: true, mask: [page.locator('input[type=password]')] })
}

test('tab storage, reload, legacy credential retirement and cross-tab revocation', async ({ page, context, request }, info) => {
  test.skip(info.project.name !== 'desktop')
  await page.goto('/')
  await page.evaluate(value => localStorage.setItem('bwip_access_token', value), process.env.QA_EXPIRED_TOKEN!)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('bwip_access_token'))).toBeNull()
  await signIn(page)
  const saved = await token(page)
  expect(saved).toBeTruthy()
  expect(await page.evaluate(() => localStorage.getItem('bwip_access_token'))).toBeNull()
  expect((await context.cookies()).length).toBe(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
  expect(await token(page)).toBe(saved)
  const other = await context.newPage() // Independent tab with no opener.
  await other.goto('/')
  await expect(other.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect(await token(other)).toBeNull()
  await signIn(other)
  const otherToken = await token(other)
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect(await token(page)).toBeNull()
  expect((await request.get(`${api}/auth/me`, { headers: { Authorization: `Bearer ${otherToken}` } })).status()).toBe(401)
  await other.reload()
  await expect(other.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect(await token(other)).toBeNull()
  await signIn(other)
  await other.close()
  const replacement = await context.newPage()
  await replacement.goto('/')
  await expect(replacement.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect(await token(replacement)).toBeNull()
})

test('login errors, logout revokes server credential, expired authentication', async ({ page, request }, info) => {
  test.skip(info.project.name !== 'desktop')
  await page.goto('/'); await page.getByLabel('Email', { exact: true }).fill('member@example.com')
  await page.getByLabel('Password', { exact: true }).fill('incorrect-synthetic-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Incorrect email or password')
  await shot(page, 'login-error-redacted')
  await page.getByLabel('Password', { exact: true }).fill('Synthetic-QA-password-2026')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
  const old = await token(page)
  await page.route('**/auth/logout', route => route.abort('failed'))
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('alert')).toContainText('backend could not be reached')
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
  expect((await request.get(`${api}/auth/me`, { headers: { Authorization: `Bearer ${old}` } })).status()).toBe(200)
  await page.unroute('**/auth/logout')
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect((await request.get(`${api}/auth/me`, { headers: { Authorization: `Bearer ${old}` } })).status()).toBe(401)
  await page.evaluate(value => sessionStorage.setItem('bwip_access_token', value), process.env.QA_EXPIRED_TOKEN!)
  await page.goto('/requirement-intelligence/' + ids.requirements[0])
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('bwip_access_token'))).toBeNull()
})

