test('human signal and candidate acceptance/rejection and evidence rejection stay explicit', async ({ page, request }, info) => {
  test.skip(info.project.name !== 'desktop')
  await signIn(page); page.on('dialog', dialog => dialog.accept())
  const headers = { Authorization: `Bearer ${await token(page)}` }
  const leadList = `${api}/leads/company/${ids.companies[0]}`
  const beforeResponse = await request.get(leadList, { headers })
  expect(beforeResponse.status()).toBe(200)
  const before = await beforeResponse.json()
  for (const decision of ['Accept candidate', 'Reject candidate', 'Reject signal']) {
    const response = await request.post(`${api}/market-signals`, { headers, data: {
      organization_id: ids.orgs[0], company_id: ids.companies[0], title: `Synthetic ${decision}`,
      signal_type: 'LOGISTICS_EXPANSION', source_type: 'NEWS', confidence_level: 'HIGH',
    } })
    expect(response.status()).toBe(201)
    const signal = await response.json()
    await page.goto('/market-intelligence/' + signal.id)
    await page.getByRole('button', { name: 'Begin signal review', exact: true }).click()
    if (decision === 'Reject signal') {
      await page.getByRole('button', { name: decision, exact: true }).click()
      await expect(page.getByRole('button', { name: 'Verify signal', exact: true })).toHaveCount(0)
      expect((await (await request.get(`${api}/market-signals/${signal.id}`, { headers })).json()).status).toBe('REJECTED')
      continue
    }
    await page.getByRole('button', { name: 'Verify signal', exact: true }).click()
    await page.getByRole('button', { name: 'Create requirement candidate', exact: true }).click()
    await page.getByRole('button', { name: 'Begin candidate review', exact: true }).click()
    await page.getByRole('button', { name: decision, exact: true }).click()
    if (decision === 'Accept candidate') {
      await expect(page.getByRole('button', { name: 'Convert to Lead + Requirement', exact: true })).toBeVisible()
    } else {
      await expect(page.getByRole('button', { name: 'Accept candidate', exact: true })).toHaveCount(0)
      await expect(page.getByRole('button', { name: 'Convert to Lead + Requirement', exact: true })).toHaveCount(0)
    }
  }
  const afterResponse = await request.get(leadList, { headers })
  expect(afterResponse.status()).toBe(200)
  const after = await afterResponse.json()
  expect(after).toEqual(before) // Acceptance alone must not create a commercial lead.
  await page.goto('/requirement-intelligence/' + ids.requirements[0])
  await page.getByLabel('Source', { exact: true }).fill('Synthetic rejected assertion')
  await page.getByLabel('Observed evidence', { exact: true }).fill('Synthetic assertion rejected by reviewer')
  await page.getByRole('button', { name: 'Add unverified evidence', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mark reviewed', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reject evidence', exact: true }).last().click()
  await expect(page.getByRole('button', { name: 'Mark reviewed', exact: true })).toHaveCount(0)
  await expect(page.locator('.requirement-evidence-heading').getByText('REJECTED', { exact: true })).toBeVisible()
})

test('requirement intelligence list, search and status filtering without stale results', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop')
  await signIn(page)
  await page.goto('/requirement-intelligence')
  await expect(page.locator('main').getByRole('heading', { name: 'Requirement Intelligence', exact: true })).toBeVisible()
  const orgSelect = page.getByLabel('Select organization', { exact: true })
  await expect(orgSelect).toBeVisible()
  await orgSelect.selectOption(String(ids.orgs[0]))
  await page.waitForResponse(r => r.url().includes('/requirement-intelligence?') && r.request().method() === 'GET')
  // Org A may have additional synthetic requirements created by earlier explicit-conversion browser flows.
  // Require at least the seeded Synthetic Demand A, assert Synthetic Demand B is not shown in org A view.
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand B', exact: true })).toHaveCount(0)
  const countText = await page.locator('.record-count').textContent()
  expect(countText).toMatch(/\d+ loaded requirement/)
  const cardCount = await page.locator('.requirement-card').count()
  expect(cardCount).toBeGreaterThanOrEqual(1)
  await expect(page.locator('.requirement-card').first()).toBeVisible()
  const search = page.getByLabel('Search requirements', { exact: true })
  const statusSelect = page.getByLabel('Filter by requirement status', { exact: true })
  async function waitForListStable() {
    // Debounced search (180ms) + network; wait for next GET to complete then UI to settle.
    await page.waitForTimeout(300)
    await expect(page.getByText('Loading requirement intelligence...')).toHaveCount(0)
  }
  await search.fill('Synthetic Demand A')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand B', exact: true })).toHaveCount(0)
  await expect(page.locator('.requirement-card').filter({ hasText: 'Synthetic Demand A' })).toHaveCount(1)
  await search.fill('Synthetic Demand B')
  await waitForListStable()
  await expect(page.getByText('No requirements match this view', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toHaveCount(0)
  await search.fill('')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toBeVisible()
  await statusSelect.selectOption('ACTIVE')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toBeVisible()
  await expect(page.locator('.requirement-card').filter({ hasText: 'Synthetic Demand A' })).toHaveCount(1)
  // A preceding candidate-conversion flow may have created an additional DRAFT requirement (Synthetic candidate 0).
  // Selecting DRAFT should therefore either show that synthetic record or correctly pass-through as ACTIVE-filtered view.
  // Verify the semantic: ACTIVE still contains Synthetic Demand A, DRAFT does NOT contain Synthetic Demand A (it is ACTIVE),
  // and CLOSED is empty (no closed demands seeded). Use CLOSED as the empty-filter probe instead of DRAFT.
  await statusSelect.selectOption('DRAFT')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toHaveCount(0)
  // DRAFT may show the converted candidate requirement; assert that if DRAFT list is non-empty it does not bleed ACTIVE records.
  const draftCards = await page.locator('.requirement-card').count()
  if (draftCards > 0) {
    await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toHaveCount(0)
    // If a DRAFT synthetic candidate exists, ensure its status chip reads DRAFT.
    await expect(page.locator('.f5-chip').filter({ hasText: 'DRAFT' }).first()).toBeVisible()
  } else {
    await expect(page.getByText('No requirements match this view', { exact: true })).toBeVisible()
  }
  await statusSelect.selectOption('CLOSED')
  await waitForListStable()
  await expect(page.getByText('No requirements match this view', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toHaveCount(0)
  await statusSelect.selectOption('ALL')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toBeVisible()
  await search.fill('No synthetic requirement matches this')
  await waitForListStable()
  await expect(page.getByText('No requirements match this view', { exact: true })).toBeVisible()
  await expect(page.locator('.requirement-card')).toHaveCount(0)
  await search.fill('')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toBeVisible()
  await page.route('**/requirement-intelligence?*', async route => {
    const result = await route.fetch()
    if (new URL(route.request().url()).searchParams.get('organization_id') === String(ids.orgs[0])) await new Promise(r => setTimeout(r, 600))
    await route.fulfill({ response: result })
  })
  await orgSelect.selectOption(String(ids.orgs[0]))
  await orgSelect.selectOption(String(ids.orgs[1]))
  await expect(page.getByRole('heading', { name: 'Synthetic Demand B', exact: true })).toBeVisible()
  await page.waitForTimeout(800)
  await expect(page.getByRole('heading', { name: 'Synthetic Demand A', exact: true })).toHaveCount(0)
  await expect(page.locator('.requirement-card')).toHaveCount(1)
  await expect(page.getByText('No requirements match this view', { exact: true })).toHaveCount(0)
  await page.unroute('**/requirement-intelligence?*')
  await search.fill('Synthetic Demand B')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand B', exact: true })).toBeVisible()
  await expect(page.locator('.requirement-card')).toHaveCount(1)
  await search.fill('Synthetic Demand A')
  await waitForListStable()
  await expect(page.getByText('No requirements match this view', { exact: true })).toBeVisible()
  await search.fill('')
  await waitForListStable()
  await expect(page.getByRole('heading', { name: 'Synthetic Demand B', exact: true })).toBeVisible()
  await shot(page, 'requirement-organization-b-no-stale-a')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
})
